/**
 * Initialize sample data in localStorage if no data exists
 */
export function initializeSampleData(): void {
  if (typeof window === 'undefined') return;
  
  const existing = localStorage.getItem('subscription-manager-subscriptions');
  if (!existing || JSON.parse(existing).length === 0) {
    localStorage.setItem('subscription-manager-subscriptions', JSON.stringify(sampleSubscriptions));
  }
}
